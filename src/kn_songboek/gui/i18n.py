def size_text(n: int) -> str:
    for unit, f in (("GB", 1 << 30), ("MB", 1 << 20)):
        if n >= f:
            return "%.1f %s" % (n / f, unit)
    return "%d KB" % (n // 1024)


def has_key(key: str) -> bool:
    return key in TEXTS


WINDOWS = sys.platform.startswith("win")


def tr(lang: str, key: str, **kw) -> str:
    """The text in this language. A text that differs on Windows (other keys, Verkenner instead of Finder)
    has its own key ending in _win; on Windows that one is used, so Mac and Windows each see only their own."""
    if WINDOWS and key + "_win" in TEXTS:
        key += "_win"
    nl, en = TEXTS.get(key, (key, key))
    text = en if lang == "en" else nl
    return text.format(**kw) if kw else text
