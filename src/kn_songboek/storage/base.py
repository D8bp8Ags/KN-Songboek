"""The storage port. The core only talks to this interface, so a mounted SD card, a folder with a
copy of a card, a FAT16 image file or an in-memory card for tests are interchangeable."""
from __future__ import annotations

from typing import List, Optional, Protocol, runtime_checkable


@runtime_checkable
class Storage(Protocol):
    """Card paths are '/'-separated and relative to the card root; matching is case-insensitive
    (FAT semantics)."""

    def read(self, path: str) -> bytes: ...
    def write(self, path: str, data: bytes) -> None: ...      # creates parent folders
    def exists(self, path: str) -> bool: ...
    def listdir(self, path: str) -> List[str]: ...            # [] if the folder does not exist
    def move(self, src: str, dst: str) -> None: ...
    def copy(self, src: str, dst: str) -> None: ...
    def remove(self, path: str) -> None: ...
    def describe(self) -> str: ...
    def isdir(self, path: str) -> bool: ...
    def size(self, path: str) -> int: ...
    def free_bytes(self) -> Optional[int]: ...                # None if unknown
    def total_bytes(self) -> Optional[int]: ...               # size of the card; None if unknown
    def writable(self) -> bool: ...                           # False if write-protected / read-only
