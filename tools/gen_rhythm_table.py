"""Generate src/kn_songboek/formats/rhythm_table.py: the KN7000's built-in rhythms and their meter.

Usage:  python3 tools/gen_rhythm_table.py <folder with the KN7000 rhythm sources>

Reads three facts out of the typed rhythm data in that folder and writes them as plain
data; no code is taken from it (ADR-0004):

* the style-ID index the firmware uses (the table ROM's copy, ``TrCopyStyleIndex`` in src/table.s):
  2048 entries, entry ``((id & 0xF00) >> 1) | (id & 0x7F)`` -> an IC18 style, a table-ROM style or
  another entry (one hop);
* per style its 13-character name (the ``.ascii`` after its label);
* per style the beats in a bar of VARIATION 1 (the third argument of its ``..._Var1`` ``var_head``).
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

SIDX = re.compile(r"^\s*sidx_(style|alias|table)\s+(0x[0-9a-fA-F]+|\d+)")
TABLE_ENTRY = re.compile(r"^\s*\.be24\s+(Style_\w+)\s+-\s+(TechnicsRhythms|BuiltinStyleSubTable)")
INCLUDE = re.compile(r'^\s*\.include\s+"(src/(?:ic18|table)/styles/[^"]+\.s)"')


def style_facts(path: Path):
    """{label: (name, beats)} for every style in one style source file."""
    text = path.read_text(encoding="utf-8").splitlines()
    out, label = {}, None
    for i, line in enumerate(text):
        m = re.match(r"^(Style_\w+):$", line)
        if m and "_" not in m.group(1)[len("Style_"):]:
            label = m.group(1)
            name = re.search(r'\.ascii\s+"([^"]*)"', text[i + 1]).group(1).strip()
            out[label] = [name, None]
        m = re.match(r"^\s*var_head\s+(Style_\w+)_Var1,\s*(\d+),\s*(\d+)", line)
        if m:
            out[m.group(1)][1] = int(m.group(3))
    return out


def main(root: Path) -> None:
    facts = {}
    for src in (root / "src/ic18/rhythm.s", root / "src/table.s"):
        for line in src.read_text(encoding="utf-8").splitlines():
            m = INCLUDE.match(line)
            if m:
                facts.update(style_facts(root / m.group(1)))

    def table(src: Path, label: str, base: str):
        """The style labels listed after ``label:``, in order."""
        lines = src.read_text(encoding="utf-8").splitlines()
        out = []
        for line in lines[lines.index(label + ":") + 1:]:
            m = TABLE_ENTRY.match(line)
            if m and m.group(2) == base:
                out.append(m.group(1))
            elif line.strip() and not line.strip().startswith("#"):
                break
        return out

    ic18 = table(root / "src/ic18/rhythm.s", "RhythmStyleTable", "TechnicsRhythms")
    rom = table(root / "src/table.s", "BuiltinStyleSubTable", "BuiltinStyleSubTable")
    assert (len(ic18), len(rom)) == (169, 52), (len(ic18), len(rom))
    lines = (root / "src/table.s").read_text(encoding="utf-8").splitlines()
    start = lines.index("TrCopyStyleIndex:")
    index = []
    for line in lines[start + 1:]:
        m = SIDX.match(line)
        if not m:
            break
        index.append((m.group(1), int(m.group(2), 0)))
    assert len(index) == 2048, len(index)

    labels = []                      # the styles in the order of the generated table
    def number(label):
        if label not in labels:
            labels.append(label)
        return labels.index(label)

    def resolve(entry, hops=0):
        kind, n = index[entry]
        if kind == "style":
            return number(ic18[n])
        if kind == "table":
            return number(rom[n])
        assert hops == 0
        return resolve(n, 1)

    resolved = [resolve(e) for e in range(2048)]
    styles = [tuple(facts[label]) for label in labels]
    assert all(b in (1, 2, 3, 4, 5, 6, 7, 8) for _, b in styles)

    out = ['"""The KN7000\'s built-in rhythms: name and beats in a bar. GENERATED by tools/gen_rhythm_table.py.',
           "",
           "Facts read from the KN7000's rhythm data; see docs/nl/reference/songbestanden.md, Maatsoort.",
           '"""',
           "",
           "# (name as the keyboard shows it, beats in a bar of VARIATION 1)",
           "STYLES = ("]
    out += ["    (%r, %d)," % s for s in styles]
    out += [")", "",
            "# style-ID index: entry ((id & 0xF00) >> 1) | (id & 0x7F) -> position in STYLES",
            "INDEX = bytes.fromhex("]
    hexs = bytes(resolved).hex()
    out += ['    "%s"' % hexs[i:i + 96] for i in range(0, len(hexs), 96)]
    out += [")", ""]
    dest = Path(__file__).resolve().parent.parent / "src/kn_songboek/formats/rhythm_table.py"
    dest.write_text("\n".join(out), encoding="utf-8")
    print("%d styles, %d index entries -> %s" % (len(styles), len(resolved), dest))


if __name__ == "__main__":
    main(Path(sys.argv[1]))
